// Purano Dhun — build the one-shot "festive upgrade" SQL for an already-live
// database that predates the festival feature.
//
// The canonical seed lives in supabase/seed.sql, but that file pins ids and is
// only safe on an empty database. Existing deployments need just the *new*
// rows, applied on top of 0007 + 0008. This script extracts them so the two
// never drift:
//
//   node supabase/tools/build_festive_upgrade.mjs
//
// Outputs (both committed so the SQL editor can copy-paste them):
//   supabase/deploy/festive_seed.sql     — festival artists/songs + links (idempotent)
//   supabase/deploy/upgrade_festive.sql  — 0007 + 0008 + festive_seed, one paste

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const supa = join(here, '..');
const deploy = join(supa, 'deploy');

const ARTIST_COLS =
  'id, display_name, display_name_ne, biography, biography_ne, profile_image, verification_status, created_at, updated_at';
const SONG_COLS =
  'id, title, title_ne, romanized_title, artist_id, featured_artists, composer, lyricist, album, film_or_source, release_year, language, primary_genre_id, mood_tags, decade, duration_seconds, artwork_url, playback_provider, provider_video_id, provider_url, source_url, attribution, metadata_verification_status, publication_status, play_count, is_featured, featured_order, created_at, updated_at';

const idOf = (row) => Number(/^\((\d+),/.exec(row.trim())[1]);

const seed = readFileSync(join(supa, 'seed.sql'), 'utf8').split('\n');

const baseLines = [];
const festiveArtists = [];
const festiveSongs = [];
const festivalUpdates = [];

let i = 0;
while (i < seed.length) {
  const line = seed[i];
  const t = line.trim();
  const isArtistInsert = /^insert into public\.artists\s*\(/i.test(t);
  const isSongInsert = /^insert into public\.songs\s*\(/i.test(t);

  if (isArtistInsert || isSongInsert) {
    const block = [];
    while (i < seed.length) {
      block.push(seed[i]);
      const done = seed[i].trim().endsWith(';');
      i += 1;
      if (done) break;
    }
    const header = block[0];
    const rows = block.slice(1)
      .map((b) => b.trim())
      .filter((b) => b.startsWith('('))
      .map((b) => b.replace(/[;,]\s*$/, ''));
    const threshold = isArtistInsert ? 28 : 1001;
    const baseRows = rows.filter((r) => idOf(r) < threshold);
    const festRows = rows.filter((r) => idOf(r) >= threshold);
    (isArtistInsert ? festiveArtists : festiveSongs).push(...festRows);
    if (baseRows.length) {
      baseLines.push(header);
      baseRows.forEach((r, idx) => baseLines.push(`    ${r}${idx === baseRows.length - 1 ? ';' : ','}`));
    }
    continue;
  }

  if (/^update public\.songs\b/i.test(t)) {
    const block = [];
    while (i < seed.length) {
      block.push(seed[i]);
      const done = seed[i].trim().endsWith(';');
      i += 1;
      if (done) break;
    }
    festivalUpdates.push(block.join('\n'));
    continue; // festival links belong to the upgrade, not the base seed
  }

  baseLines.push(line);
  i += 1;
}

const formatRows = (rows) => rows.map((r, idx) => `    ${r}${idx === rows.length - 1 ? '' : ','}`).join('\n');

const festiveSeedSql = `-- Purano Dhun — festive seed for existing databases (generated).
-- Run AFTER 0007_festival_features.sql and 0008_festival_calendar.sql.
-- Idempotent: safe to re-run. Regenerate with
--   node supabase/tools/build_festive_upgrade.mjs

begin;

-- Festival artists (28-59)
insert into public.artists (${ARTIST_COLS}) values
${formatRows(festiveArtists)}
on conflict (id) do nothing;

-- Festive songs (1001-1061)
insert into public.songs (${SONG_COLS}) values
${formatRows(festiveSongs)}
on conflict (id) do nothing;

-- Tag songs with their festival
${festivalUpdates.join('\n\n')}

commit;
`;

mkdirSync(deploy, { recursive: true });
writeFileSync(join(deploy, 'festive_seed.sql'), festiveSeedSql);

const migration = (name) => readFileSync(join(supa, 'migrations', name), 'utf8');

const upgradeSql = `-- Purano Dhun — one-shot festive upgrade for an already-live database.
--
-- GENERATED by supabase/tools/build_festive_upgrade.mjs — do not hand-edit.
-- Paste this whole file into the Supabase SQL Editor (or run it with
-- \`supabase db execute -f supabase/deploy/upgrade_festive.sql\`) to bring a
-- database that predates the festival feature fully up to date.
--
-- It is safe to re-run. It applies, in order:
--   1. 0006_abuse_controls.sql     (throttles + PII-safe audit notes)
--   2. 0007_festival_features.sql  (festival taxonomy + RPCs)
--   3. 0008_festival_calendar.sql  (dates, calendar RPC, playlist RPC)
--   4. 0009_song_requests.sql      (public "recommend a song" workflow)
--   5. festive_seed.sql            (festival artists/songs + links)

-- ===========================================================================
-- 1. 0006_abuse_controls.sql
-- ===========================================================================
${migration('0006_abuse_controls.sql')}

-- ===========================================================================
-- 2. 0007_festival_features.sql
-- ===========================================================================
${migration('0007_festival_features.sql')}

-- ===========================================================================
-- 3. 0008_festival_calendar.sql
-- ===========================================================================
${migration('0008_festival_calendar.sql')}

-- ===========================================================================
-- 4. 0009_song_requests.sql
-- ===========================================================================
${migration('0009_song_requests.sql')}

-- ===========================================================================
-- 5. festive_seed.sql
-- ===========================================================================
${festiveSeedSql}
`;

writeFileSync(join(deploy, 'upgrade_festive.sql'), upgradeSql);

// Test-only artifact: the base seed as it would look on the live DB before the
// festival feature (used by tools/verify_upgrade.mjs).
writeFileSync(join(here, 'base_seed_only.sql'), baseLines.join('\n'));

console.error(`festive artists: ${festiveArtists.length}`);
console.error(`festive songs:   ${festiveSongs.length}`);
console.error(`festival links:  ${festivalUpdates.length} statement(s)`);
console.error('wrote supabase/deploy/festive_seed.sql and supabase/deploy/upgrade_festive.sql');
