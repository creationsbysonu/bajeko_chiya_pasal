create table public.genre_categories (
    id            bigint generated by default as identity primary key,
    slug          text        not null unique,
    name          text        not null unique,
    name_ne       text        not null default '',
    description   text        not null default '',
    display_order integer     not null default 0,
    is_active     boolean     not null default true,
    created_at    timestamptz not null default now()
);
create index on public.genre_categories (display_order);

create table public.genres (
    id          bigint generated by default as identity primary key,
    name        text        not null unique,
    name_ne     text        not null default '',
    slug        text        not null unique,
    category    text        not null default 'popular',
    description text        not null default '',
    is_active   boolean     not null default true,
    created_at  timestamptz not null default now(),
    constraint genre_category_format check (category ~ '^[a-z0-9_]*$')
);
create index on public.genres (category);

