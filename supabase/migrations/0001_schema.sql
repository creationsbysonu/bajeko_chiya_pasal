    updated_at        timestamptz not null default now(),
    constraint artist_verification_status_check
        check (verification_status in ('unverified', 'verified', 'official'))
);
create index on public.artists (display_name);
create index on public.artists (display_name_ne);

create table public.songs (
    id            bigint generated by default as identity primary key,
    title         text        not null,
    title_ne      text        not null default '',
    romanized_title text      not null default '',
    artist_id     bigint      not null references public.artists (id) on delete cascade,
    featured_artists text     not null default '',
    composer      text        not null default '',
    lyricist      text        not null default '',
    album         text        not null default '',
    film_or_source text       not null default '',
    release_year  integer,
    language      text        not null default 'Nepali',
    primary_genre_id bigint references public.genres (id) on delete set null,
    mood_tags     jsonb       not null default '[]'::jsonb,
    decade        text        not null default '',
    duration_seconds integer,
    artwork_url   text        not null default '',
    playback_provider text    not null default 'youtube',
    provider_video_id text    not null,
    provider_url  text        not null default '',
    source_url    text        not null default '',
    attribution   text        not null default '',
    metadata_verification_status text not null default 'demo',
    publication_status text    not null default 'published',
    play_count    integer     not null default 0,
    is_featured   boolean     not null default false,
    featured_order integer    not null default 0,
    created_at    timestamptz not null default now(),
    updated_at    timestamptz not null default now(),
    constraint song_verification_status_check
        check (metadata_verification_status in ('verified', 'community_submitted', 'demo')),
    constraint song_publication_status_check
        check (publication_status in ('published', 'draft', 'disputed', 'taken_down')),
    constraint song_play_count_check check (play_count >= 0),
    constraint song_release_year_check
        check (release_year is null or (release_year >= 1900 and release_year <= 2200))
