create index on public.songs (title);
create index on public.songs (title_ne);
create index on public.songs (romanized_title);
create index on public.songs (decade);
create index on public.songs (language);
create index on public.songs (publication_status);
create index on public.songs (provider_video_id);
create index on public.songs (release_year);
create index on public.songs (metadata_verification_status);
create index on public.songs (artist_id);
create index on public.songs (primary_genre_id);
create index on public.songs (is_featured);

-- Keep `decade` in step with `release_year`, exactly like the old Django
-- Model.save() did (only when the decade was not set explicitly).
create or replace function public.song_sync_decade()
returns trigger
language plpgsql
as $$
begin
    if new.release_year is not null and coalesce(new.decade, '') = '' then
        new.decade := (new.release_year / 10 * 10)::text || 's';
    end if;
    new.updated_at := now();
    return new;
end;
$$;

create trigger songs_sync_decade
    before insert or update on public.songs
    for each row execute function public.song_sync_decade();

create table public.song_secondary_genres (
    song_id bigint not null references public.songs (id) on delete cascade,
    genre_id bigint not null references public.genres (id) on delete cascade,
    primary key (song_id, genre_id)
);
create index on public.song_secondary_genres (genre_id);

