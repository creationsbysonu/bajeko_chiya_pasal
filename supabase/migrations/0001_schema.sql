create table public.stations (
    id            bigint generated by default as identity primary key,
    slug          text        not null unique,
    title         text        not null,
    title_ne      text        not null default '',
    tagline       text        not null default '',
    tagline_ne    text        not null default '',
    description   text        not null default '',
    description_ne text       not null default '',
    cover_image   text        not null default '',
    theme_color   text        not null default '#C7A66A',
    ambient_type  text        not null default 'vintage_crackle',
    is_featured   boolean     not null default true,
    is_active     boolean     not null default true,
    display_order integer     not null default 0,
    created_at    timestamptz not null default now(),
    updated_at    timestamptz not null default now()
);
create index on public.stations (display_order);

create table public.station_songs (
    id         bigint generated by default as identity primary key,
    station_id bigint not null references public.stations (id) on delete cascade,
    song_id    bigint not null references public.songs (id) on delete cascade,
    position   integer not null default 0,
    added_at   timestamptz not null default now(),
    unique (station_id, song_id)
);
create index on public.station_songs (station_id, position);
create index on public.station_songs (song_id);

-- ---------------------------------------------------------------------------
-- Listener data
-- ---------------------------------------------------------------------------

create table public.favorites (
    id         bigint generated by default as identity primary key,
    user_id    uuid    not null,
    song_id    bigint  not null references public.songs (id) on delete cascade,
    created_at timestamptz not null default now(),
    unique (user_id, song_id)
);
create index on public.favorites (user_id);
create index on public.favorites (song_id);

create table public.playback_events (
    id            bigint generated by default as identity primary key,
    event_type    text not null,
    song_id       bigint references public.songs (id) on delete set null,
    station_id    bigint references public.stations (id) on delete set null,
    session_id    text not null default '',
    error_message text not null default '',
    timestamp     timestamptz not null default now(),
    constraint playback_event_type_check
        check (event_type in ('start', 'complete', 'skip', 'error'))
);
create index on public.playback_events (timestamp);
create index on public.playback_events (event_type);
create index on public.playback_events (song_id);

-- ---------------------------------------------------------------------------
-- Copyright / takedown workflow
-- ---------------------------------------------------------------------------

create table public.takedown_requests (
    id               bigint generated by default as identity primary key,
    song_id          bigint not null references public.songs (id) on delete cascade,
    claimant_name    text not null,
    claimant_email   text not null,
    reason           text not null,
    details          text not null default '',
    status           text not null default 'pending',
    resolution_notes text not null default '',
    created_at       timestamptz not null default now(),
    resolved_at      timestamptz,
    constraint takedown_reason_check
        check (reason in ('copyright', 'broken_video', 'wrong_metadata', 'other')),
    constraint takedown_status_check
        check (status in ('pending', 'under_review', 'content_unpublished', 'resolved_kept', 'rejected'))
);
create index on public.takedown_requests (status);
create index on public.takedown_requests (created_at);

