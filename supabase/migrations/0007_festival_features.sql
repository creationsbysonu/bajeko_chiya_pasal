-- NOTE: the seed-time links between festivals and songs live in seed.sql, not
-- here: migrations run *before* seed.sql, so referencing seeded song/artist ids
-- from a migration would violate foreign keys on a fresh database.

create or replace function public.get_festival_categories()
returns jsonb
language sql
stable
security definer
set search_path = public, pg_temp
as $$
    select coalesce(jsonb_agg(fc order by fc.display_order, fc.name), '[]'::jsonb)
    from public.festival_categories fc
    where fc.is_active;
$$;


-- Fetch the best-matching festive songs for a festival, sorted by play_count.
create or replace function public.get_festival_songs(p_festival_slug text, p_limit int default 24)
returns jsonb
language plpgsql
stable
security definer
set search_path = public, pg_temp
as $$
declare
    v_count     bigint;
    v_results   jsonb;
    v_festival  bigint;
begin
    v_festival := (select id from public.festival_categories where slug = p_festival_slug and is_active);

    select count(*) into v_count
    from public.songs s
    where s.festival_id = v_festival
      and s.publication_status = 'published';

    select coalesce(jsonb_agg(sp.song order by sp.play_count desc nulls last, sp.id desc), '[]'::jsonb)
    into v_results
    from (
        select
            s.play_count as play_count,
            s.id as id,
            jsonb_build_object(
                'id', s.id,
                'title', s.title,
                'title_ne', s.title_ne,
                'artist_name', a.display_name,
                'artist_name_ne', a.display_name_ne,
                'primary_genre_name', g.name,
                'primary_genre_category', g.category,
                'mood_tags', s.mood_tags,
                'release_year', s.release_year,
                'duration_seconds', s.duration_seconds,
                'artwork_url', s.artwork_url,
                'play_count', s.play_count,
                'is_featured', s.is_featured,
                'featured_order', s.featured_order
            ) as song
        from public.songs s
        join public.artists a on a.id = s.artist_id
        left join public.genres g on g.id = s.primary_genre_id
        where s.festival_id = v_festival
          and s.publication_status = 'published'
        order by s.play_count desc nulls last, s.id desc
        limit least(greatest(coalesce(p_limit, 24), 1), 100)
    ) sp;

    return jsonb_build_object('count', v_count, 'results', v_results);
end;
$$;

