-- Bajeko Chiya Pasal — 0009_song_requests.sql
--
-- "Recommend a song" feature: an unauthenticated visitor can suggest a song we
-- should add to the catalog. Mirrors the takedown workflow (0006) so the abuse
-- story is identical:
--
--   * the table is RLS-locked (0004) and only reachable through SECURITY DEFINER
--     RPCs, so no email or internal note is ever exposed to the browser;
--   * submissions are validated first, then throttled (8/hour per email or per
--     anonymous listener session);
--   * every accepted suggestion is written to the audit trail;
--   * a small public feed powers a "recently suggested" list on the site, while
--     the full queue (with requester contact + admin notes) is admin-only.
--
-- Idempotent: safe to re-run, and safe to apply on a database that already has
-- the festival feature (it does not depend on 0007/0008).

begin;

-- ---------------------------------------------------------------------------
-- Table
-- ---------------------------------------------------------------------------

create table if not exists public.song_requests (
    id              bigint generated by default as identity primary key,
    title           text not null,
    artist          text not null default '',
    youtube_url     text not null default '',
    festival_id     bigint references public.festival_categories (id) on delete set null,
    genre_id        bigint references public.genres (id) on delete set null,
    note            text not null default '',
    requester_name  text not null,
    requester_email text not null default '',
    status          text not null default 'pending',
    admin_notes     text not null default '',
    reporter_id     uuid,
    created_at      timestamptz not null default now(),
    resolved_at     timestamptz,
    constraint song_request_status_check
        check (status in ('pending', 'under_review', 'added', 'rejected'))
);
create index if not exists song_requests_status_idx on public.song_requests (status);
create index if not exists song_requests_created_idx on public.song_requests (created_at);
create index if not exists song_requests_email_time_idx on public.song_requests (requester_email, created_at);
create index if not exists song_requests_reporter_time_idx on public.song_requests (reporter_id, created_at);

alter table public.song_requests enable row level security;

-- ---------------------------------------------------------------------------
-- 1. submit_song_request: validated, throttled, audited public submission
-- ---------------------------------------------------------------------------

create or replace function public.submit_song_request(
    p_title          text,
    p_artist         text default '',
    p_youtube_url    text default '',
    p_festival_slug  text default '',
    p_genre_id       bigint default null,
    p_note           text default '',
    p_requester_name text default '',
    p_requester_email text default ''
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    v_request_id bigint;
    v_uid        uuid := auth.uid();
    v_email      text;
    v_url        text := btrim(coalesce(p_youtube_url, ''));
    v_slug       text := btrim(coalesce(p_festival_slug, ''));
    v_festival   bigint;
    v_recent     integer;
begin
    -- --- validation (before the throttle, so bad input never probes it) -----
    if p_title is null or btrim(p_title) = '' then
        raise exception 'title: This field is required.';
    end if;
    if length(btrim(p_title)) > 300 then
        raise exception 'title: Keep the song title under 300 characters.';
    end if;
    if p_requester_name is null or btrim(p_requester_name) = '' then
        raise exception 'requester_name: This field is required.';
    end if;
    if length(btrim(p_requester_name)) > 200 then
        raise exception 'requester_name: Keep your name under 200 characters.';
    end if;

    v_email := lower(btrim(coalesce(p_requester_email, '')));
    if v_email <> '' then
        if length(v_email) > 320 or v_email !~ '^[^@]+@[^@]+\.[^@]+$' then
            raise exception 'requester_email: Enter a valid email address.';
        end if;
    end if;

    if v_url <> '' and v_url !~* '^https?://(www\.|m\.|music\.)?(youtube\.com|youtu\.be)/' then
        raise exception 'youtube_url: Enter a valid YouTube link.';
    end if;

    if v_slug <> '' then
        select id into v_festival
        from public.festival_categories
        where slug = v_slug and is_active
        limit 1;
        if v_festival is null then
            raise exception 'festival_slug: Unknown festival.';
        end if;
    end if;

    if p_genre_id is not null and not exists (select 1 from public.genres where id = p_genre_id) then
        raise exception 'genre_id: Unknown genre.';
    end if;

    -- --- identity for throttling --------------------------------------------
    -- The throttle below keys on the requester email or the (anonymous) listener
    -- session. Without either, a caller could submit without limit, so demand one.
    -- The website always creates an anonymous session, so only direct API abuse
    -- with a bare anon key hits this.
    if v_email = '' and v_uid is null then
        raise exception 'requester_email: Add an email (or enable cookies) so suggestions can be rate-limited.';
    end if;

    -- --- throttle: 8 suggestions/hour per email or listener session ---------
    select count(*) into v_recent
    from public.song_requests
    where created_at > now() - interval '1 hour'
      and ((v_email <> '' and requester_email = v_email)
           or (v_uid is not null and reporter_id = v_uid));
    if v_recent >= 8 then
        raise exception 'Too many suggestions from this identity in the last hour. Please try again later.';
    end if;

    insert into public.song_requests
        (title, artist, youtube_url, festival_id, genre_id, note,
         requester_name, requester_email, reporter_id)
    values (
        left(btrim(p_title), 300),
        left(btrim(coalesce(p_artist, '')), 200),
        left(v_url, 500),
        v_festival,
        p_genre_id,
        left(coalesce(p_note, ''), 2000),
        left(btrim(p_requester_name), 200),
        v_email,
        v_uid
    )
    returning id into v_request_id;

    insert into public.audit_logs (actor_username, action, target_model, target_id, details)
    values (
        'public_listener',
        'SONG_REQUEST_SUBMITTED',
        'SongRequest',
        v_request_id::text,
        jsonb_build_object(
            'title', left(btrim(p_title), 300),
            'festival_slug', v_slug
        )
    );

    return jsonb_build_object(
        'message', 'Thanks! Your suggestion has been logged for review.',
        'request_id', v_request_id
    );
end;
$$;

-- ---------------------------------------------------------------------------
-- 2. get_song_requests_recent: public, contact-free "community suggestions"
-- ---------------------------------------------------------------------------

create or replace function public.get_song_requests_recent(p_limit integer default 6)
returns jsonb
language sql
stable
security definer
set search_path = public, pg_temp
as $$
    select coalesce(jsonb_agg(payload order by created_at desc), '[]'::jsonb)
    from (
        select
            sr.created_at,
            jsonb_build_object(
                'id', sr.id,
                'title', sr.title,
                'artist', sr.artist,
                'festival_name', fc.name,
                'festival_name_ne', fc.name_ne,
                'festival_slug', fc.slug,
                'status', sr.status,
                'created_at', sr.created_at
            ) as payload
        from public.song_requests sr
        left join public.festival_categories fc on fc.id = sr.festival_id
        where sr.status in ('pending', 'under_review', 'added')
        order by sr.created_at desc
        limit greatest(0, least(coalesce(p_limit, 6), 24))
    ) t;
$$;

-- ---------------------------------------------------------------------------
-- 3. admin_song_requests: the full moderation queue (admin-only)
-- ---------------------------------------------------------------------------

create or replace function public.admin_song_requests(
    p_status text default '',
    p_search text default ''
)
returns jsonb
language plpgsql
stable
security definer
set search_path = public, pg_temp
as $$
begin
    if not public.is_admin() then
        raise exception 'Admin access required';
    end if;

    return (
        select jsonb_build_object(
            'count', count(*)::bigint,
            'results', coalesce(jsonb_agg(payload order by created_at desc), '[]'::jsonb),
            'available_statuses', '["pending", "under_review", "added", "rejected"]'::jsonb
        )
        from (
            select
                sr.created_at as created_at,
                jsonb_build_object(
                    'id', sr.id,
                    'title', sr.title,
                    'artist', sr.artist,
                    'youtube_url', sr.youtube_url,
                    'festival', sr.festival_id,
                    'festival_name', fc.name,
                    'festival_slug', fc.slug,
                    'genre', sr.genre_id,
                    'note', sr.note,
                    'requester_name', sr.requester_name,
                    'requester_email', sr.requester_email,
                    'status', sr.status,
                    'admin_notes', sr.admin_notes,
                    'created_at', sr.created_at,
                    'resolved_at', sr.resolved_at
                ) as payload
            from public.song_requests sr
            left join public.festival_categories fc on fc.id = sr.festival_id
            where (coalesce(p_status, '') = '' or sr.status = p_status)
              and (
                  coalesce(p_search, '') = '' or
                  sr.title ilike '%' || p_search || '%' or
                  sr.artist ilike '%' || p_search || '%' or
                  sr.requester_name ilike '%' || p_search || '%' or
                  sr.requester_email ilike '%' || p_search || '%'
              )
        ) t
    );
end;
$$;

-- ---------------------------------------------------------------------------
-- 4. admin_song_request_action: resolve one suggestion (admin-only)
-- ---------------------------------------------------------------------------

create or replace function public.admin_song_request_action(
    p_id bigint,
    p_status text,
    p_admin_notes text default ''
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    sr public.song_requests;
begin
    if not public.is_admin() then
        raise exception 'Admin access required';
    end if;

    select * into sr from public.song_requests where id = p_id;
    if not found then
        raise exception 'Suggestion not found';
    end if;
    if p_status not in ('pending', 'under_review', 'added', 'rejected') then
        raise exception 'Invalid status';
    end if;

    update public.song_requests set
        status = p_status,
        admin_notes = left(coalesce(p_admin_notes, ''), 2000),
        resolved_at = case
            when p_status in ('added', 'rejected') then now()
            else null
        end
    where id = p_id;

    perform public._audit('SONG_REQUEST_' || upper(p_status), 'SongRequest', p_id::text, jsonb_build_object(
        'title', sr.title,
        'notes', left(coalesce(p_admin_notes, ''), 2000)
    ));

    return jsonb_build_object(
        'id', p_id,
        'status', p_status,
        'admin_notes', left(coalesce(p_admin_notes, ''), 2000)
    );
end;
$$;

commit;
