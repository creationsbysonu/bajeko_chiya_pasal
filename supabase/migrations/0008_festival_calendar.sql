-- ---------------------------------------------------------------------------
-- Festival calendar: every active festival with its next occurrence.
-- ---------------------------------------------------------------------------
create or replace function public.get_festival_calendar()
returns jsonb
language sql
stable
security definer
set search_path = public, pg_temp
as $$
    with base as (
        select
            fc.id, fc.slug, fc.name, fc.name_ne, fc.description,
            fc.display_order, fc.mood_tags,
            (select count(*) from public.songs s
              where s.festival_id = fc.id and s.publication_status = 'published') as song_count
        from public.festival_categories fc
        where fc.is_active
    ),
    occ as (
        select
            b.id,
            coalesce(future.start_date, past.start_date + interval '1 year')::date as start_date,
            coalesce(future.end_date,   past.end_date   + interval '1 year')::date as end_date,
            (future.start_date is null and past.start_date is not null) as is_estimated
        from base b
        left join lateral (
            select fd.start_date, fd.end_date
            from public.festival_dates fd
            where fd.festival_id = b.id and fd.end_date >= current_date
            order by fd.start_date asc limit 1
        ) future on true
        left join lateral (
            select fd.start_date, fd.end_date
            from public.festival_dates fd
            where fd.festival_id = b.id
            order by fd.start_date desc limit 1
        ) past on true
    )
    select coalesce(
        jsonb_agg(
            jsonb_build_object(
                'id', b.id, 'slug', b.slug, 'name', b.name, 'name_ne', b.name_ne,
                'description', b.description,
                'display_order', b.display_order, 'mood_tags', to_jsonb(b.mood_tags),
                'song_count', b.song_count,
                'start_date', o.start_date, 'end_date', o.end_date,
                'days_until_start', (o.start_date - current_date),
                'days_until_end', (o.end_date - current_date),
                'is_active_window', (o.start_date <= current_date and current_date <= o.end_date),
                'is_imminent', (o.start_date >= current_date and (o.start_date - current_date) <= 20),
                'is_estimated', o.is_estimated
            )
            order by
                case when o.start_date <= current_date and current_date <= o.end_date then 0 else 1 end,
                o.start_date asc,
                b.display_order asc
        ),
        '[]'::jsonb
    )
    from base b
    join occ o on o.id = b.id;
$$;

comment on function public.get_festival_calendar() is 'Active festivals ordered by the soonest upcoming occurrence, with countdown fields.';

-- ---------------------------------------------------------------------------
-- Festival playlist: dedicated songs first, then vibe-matched songs, then a
-- trending festive layer (popular + recent festive tracks from across the
-- catalog, so "the thing playing right now" leads the mix). Every festival
-- therefore always has a full, playable set even before it has many uploads.
-- ---------------------------------------------------------------------------
create or replace function public.get_festival_songs(p_festival_slug text, p_limit int default 24)
returns jsonb
language plpgsql
stable
security definer
set search_path = public, pg_temp
as $$
declare
    v_festival bigint;
    v_tags     text[];
    v_limit    int := least(greatest(coalesce(p_limit, 24), 1), 100);
    v_count    bigint;
    v_results  jsonb;
begin
    select id, mood_tags into v_festival, v_tags
    from public.festival_categories
    where slug = p_festival_slug and is_active;

    if v_festival is null then
        return jsonb_build_object('count', 0, 'dedicated_count', 0, 'results', '[]'::jsonb);
    end if;

    select count(*) into v_count
    from public.songs s
    where s.festival_id = v_festival and s.publication_status = 'published';

    with direct as (
        select s.id, s.play_count, s.release_year, 0 as tier, 'festival'::text as source
        from public.songs s
        where s.festival_id = v_festival and s.publication_status = 'published'
    ),
    vibe as (
        select s.id, s.play_count, s.release_year, 1 as tier, 'vibe'::text as source
        from public.songs s
        where s.publication_status = 'published'
          and s.festival_id is null
          and coalesce(cardinality(v_tags), 0) > 0
          and s.mood_tags ?| v_tags
    ),
    trending as (
        select s.id, s.play_count, s.release_year, 2 as tier, 'trending'::text as source
        from public.songs s
        where s.publication_status = 'published'
          and (s.mood_tags ? 'festive' or s.festival_id is not null)
    ),
    picked as (
        select id, play_count, release_year, tier, source from direct
        union all
        select id, play_count, release_year, tier, source from vibe
        union all
        select id, play_count, release_year, tier, source from trending
    ),
    best as (
        select distinct on (id) id, play_count, release_year, tier, source
        from picked
        order by id, tier asc
    )
    select coalesce(
        jsonb_agg(sp.song order by sp.tier asc, sp.play_count desc nulls last, sp.release_year desc nulls last, sp.id desc),
        '[]'::jsonb
    )
    into v_results
    from (
        select b.tier, b.source, s.id, s.play_count, s.release_year,
            jsonb_build_object(
                'id', s.id,
                'title', s.title,
                'title_ne', s.title_ne,
                'artist_name', a.display_name,
                'artist_name_ne', a.display_name_ne,
                'primary_genre_name', g.name,
                'primary_genre_category', g.category,
                'mood_tags', s.mood_tags,
                'release_year', s.release_year,
                'duration_seconds', s.duration_seconds,
                'artwork_url', s.artwork_url,
                'play_count', s.play_count,
                'is_featured', s.is_featured,
                'featured_order', s.featured_order,
                'playback_provider', s.playback_provider,
                'provider_video_id', s.provider_video_id,
                'provider_url', s.provider_url,
                'source', b.source
            ) as song
        from (
            select id, play_count, release_year, tier, source
            from best
            order by tier asc, play_count desc nulls last, release_year desc nulls last, id desc
            limit v_limit
        ) b
        join public.songs s on s.id = b.id
        join public.artists a on a.id = s.artist_id
        left join public.genres g on g.id = s.primary_genre_id
    ) sp;

    return jsonb_build_object(
        'count', coalesce(jsonb_array_length(v_results), 0),
        'dedicated_count', v_count,
        'results', v_results
    );
end;
$$;

comment on function public.get_festival_songs(text, int) is 'Festival playlist: dedicated songs, then vibe-matched non-festival songs, then trending festive tracks.';

