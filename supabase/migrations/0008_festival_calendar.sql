-- Purano Dhun — 0008_festival_calendar.sql
-- Turns "Festive & Seasonal" into a calendar-aware experience:
--
--   * every major Nepali festival is in the taxonomy (Dashain, Tihar, Chhath,
--     Teej, Maghe Sankranti, Maha Shivaratri, Holi, Ram Navami, Buddha Jayanti,
--     Janai Purnima, Krishna Janmashtami, Gaura Parva, Gai/Indra/Bisket Jatra,
--     the Losars, Yomari Punhi, Christmas, Eid, Udhauli/Ubhauli, ...)
--   * festival_dates stores the Gregorian window for each occurrence so the
--     site can count down to the *next* celebration and start the vibe ~20
--     days early
--   * get_festival_calendar() returns the whole calendar with days-until and
--     "imminent" flags
--   * get_festival_songs() now always returns a full, playable playlist by
--     falling back to thematically-close catalog songs when a festival has
--     few dedicated uploads yet.
--
-- Dates are lunar and shift every year, so they are data (not code): add a new
-- row per festival per year as the official gazette is published. When a
-- festival has no future row, get_festival_calendar() rolls the most recent
-- occurrence forward by a year and flags it as estimated so the section never
-- goes blank.

begin;

-- ---------------------------------------------------------------------------
-- Occurrence dates
-- ---------------------------------------------------------------------------
create table if not exists public.festival_dates (
    id           bigint generated by default as identity primary key,
    festival_id  bigint not null references public.festival_categories (id) on delete cascade,
    label        text not null default '',
    start_date   date not null,
    end_date     date not null,
    is_estimated boolean not null default false,
    created_at   timestamptz not null default now(),
    constraint festival_dates_span check (end_date >= start_date),
    constraint festival_dates_unique unique (festival_id, start_date)
);

create index if not exists idx_festival_dates_window on public.festival_dates (festival_id, start_date);

comment on table public.festival_dates is 'Gregorian date window for each occurrence of a festival (one row per festival per year).';
comment on column public.festival_dates.label is 'Human label for the occurrence, e.g. "BS 2083 / 2026".';

